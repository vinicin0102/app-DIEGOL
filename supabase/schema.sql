-- ==================================
-- COMMENTS TABLE (Comentários em posts)
-- ==================================
create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  post_id bigint references public.posts(id) on delete cascade,
  user_id uuid references public.profiles(id),
  user_name text not null default 'Atleta Anônimo',
  user_level int default 1,
  content text not null,
  created_at timestamp with time zone default timezone('utc'::text, now())
);

-- Index for faster comment lookup by post
create index if not exists idx_comments_post_id on public.comments(post_id);

-- RLS for comments
alter table public.comments enable row level security;
create policy "Comments are viewable by everyone." on public.comments for select using (true);
create policy "Authenticated users can insert comments." on public.comments for insert with check (auth.role() = 'authenticated');
create policy "Users can delete own comments." on public.comments for delete using (auth.uid() = user_id);

-- Enable realtime for comments
alter publication supabase_realtime add table comments;

